#!/usr/bin/env python3
"""Regenerates app/src/main/java/com/titanpointer/RetroCursors.java from the X11 cursor font.

The font is xorg's font-cursor-misc ("These glyphs are unencumbered"), e.g. from Debian's xfonts-base:
  apt-get download xfonts-base && dpkg-deb -x xfonts-base_*.deb deb
  zcat deb/usr/share/fonts/X11/misc/cursor.pcf.gz > cursor.pcf && pcf2bdf -o cursor.bdf cursor.pcf
  python3 scripts/retro-cursors.py cursor.bdf
Each glyph is merged with its _mask glyph; the hotspot is the glyph origin.
"""
import sys

# Pointer-like glyphs first (in this order), then every other glyph in font order.
FIRST = ['left_ptr', 'top_left_arrow', 'arrow', 'draft_large', 'draft_small', 'right_ptr', 'center_ptr', 'question_arrow',
         'hand2', 'hand1', 'pencil', 'crosshair', 'tcross', 'cross', 'plus', 'target', 'circle', 'dot', 'dotbox', 'X_cursor']
LABELS = {'left_ptr': 'Arrow', 'top_left_arrow': 'Top-left arrow', 'arrow': 'Diagonal arrow', 'draft_large': 'Draft (large)',
          'draft_small': 'Draft (small)', 'right_ptr': 'Right arrow', 'center_ptr': 'Up arrow', 'question_arrow': 'Help',
          'hand2': 'Hand', 'hand1': 'Hand 2', 'tcross': 'Thin cross', 'X_cursor': 'X', 'xterm': 'Text (I-beam)',
          'fleur': 'Move', 'coffee_mug': 'Coffee mug', 'rtl_logo': 'RTL logo', 'sb_h_double_arrow': 'Left-right arrow',
          'sb_v_double_arrow': 'Up-down arrow', 'sb_up_arrow': 'Up', 'sb_down_arrow': 'Down', 'sb_left_arrow': 'Left',
          'sb_right_arrow': 'Right', 'll_angle': 'Lower-left angle', 'lr_angle': 'Lower-right angle',
          'ul_angle': 'Upper-left angle', 'ur_angle': 'Upper-right angle', 'bogosity': 'Bogosity', 'gumby': 'Gumby',
          'trek': 'Trek', 'gobbler': 'Gobbler', 'iron_cross': 'Iron cross', 'leftbutton': 'Left button',
          'middlebutton': 'Middle button', 'rightbutton': 'Right button'}


def label(n):
    return LABELS.get(n) or n.replace('_', ' ').capitalize()
bdf = open(sys.argv[1]).read().split('STARTCHAR ')[1:]
g = {}
for ch in bdf:
    lines = ch.split('\n'); name = lines[0].strip()
    bbx = [l for l in lines if l.startswith('BBX')][0].split()[1:]
    w, h, xo, yo = map(int, bbx)
    i = lines.index('BITMAP'); rows = lines[i+1:i+1+h]
    bits = [[(int(r, 16) >> (len(r)*4 - 1 - x)) & 1 for x in range(w)] for r in rows]
    # x-down coords relative to origin: col = xo + x, row = -(yo + h) + y
    g[name] = dict(w=w, h=h, left=xo, top=-(yo + h), bits=bits)
out = {}
for n in g:
    if n.endswith('_mask'): continue
    s, m = g[n], g[n + '_mask']
    L = min(s['left'], m['left']); T = min(s['top'], m['top'])
    R = max(s['left'] + s['w'], m['left'] + m['w']); B = max(s['top'] + s['h'], m['top'] + m['h'])
    W, H = R - L, B - T
    grid = [['.'] * W for _ in range(H)]
    for gl, ch in ((m, 'o'), (s, '#')):
        for y in range(gl['h']):
            for x in range(gl['w']):
                if gl['bits'][y][x]:
                    grid[gl['top'] - T + y][gl['left'] - L + x] = ch
    out[n] = dict(w=W, h=H, hx=-L, hy=-T, rows=[''.join(r) for r in grid])

HEADER = '''package com.titanpointer;

/**
 * Pointer images from the X Window System cursor font (xorg font-cursor-misc, shipped by every Linux distro;
 * its COPYING says: "These glyphs are unencumbered"). Generated by scripts/retro-cursors.py: each glyph is its
 * shape merged with its mask. {@code #} = foreground (drawn in the chosen colour), {@code o} = mask only (outline,
 * drawn in the contrasting colour), {@code .} = transparent. The hotspot is the glyph origin from the font.
 */
final class RetroCursors {
    private RetroCursors() {}

    static final class Glyph {
        final String id, label;
        final int hotX, hotY;
        final String[] rows;

        Glyph(String id, String label, int hotX, int hotY, String... rows) {
            this.id = id;
            this.label = label;
            this.hotX = hotX;
            this.hotY = hotY;
            this.rows = rows;
        }

        int width() {
            return rows[0].length();
        }

        int height() {
            return rows.length;
        }
    }

    static final Glyph[] ALL = {'''

lines = [HEADER]
order = FIRST + [n for n in out if n not in FIRST]
for n in order:
    g = out[n]
    lines.append('            new Glyph("%s", "%s", %d, %d,' % (n, label(n), g['hx'], g['hy']))
    for i, r in enumerate(g['rows']):
        lines.append('                    "%s"%s' % (r, ',' if i < len(g['rows']) - 1 else '),'))
lines += ['    };', '', '    static Glyph find(String id) {', '        for (Glyph g : ALL) if (g.id.equals(id)) return g;',
          '        return null;', '    }', '}', '']
open('app/src/main/java/com/titanpointer/RetroCursors.java', 'w').write('\n'.join(lines))
print('wrote', len(order), 'glyphs')
